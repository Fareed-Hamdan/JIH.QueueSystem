-- ---------------------------------------------------------------- reference data

CREATE TABLE CLINICS (
    ID                  NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE                NVARCHAR2(1)   NOT NULL,          -- ticket prefix A, B, C...
    NAME_AR             NVARCHAR2(100) NOT NULL,
    NAME_EN             NVARCHAR2(100) NOT NULL,
    STATUS              NVARCHAR2(20)  NOT NULL,          -- Open | Paused | Full | Closed
    DAILY_TICKET_LIMIT  NUMBER(10),
    TICKET_CUTOFF_TIME  NVARCHAR2(5),                     -- HH:mm
    SORT_ORDER          NUMBER(10)     NOT NULL,
    IS_ACTIVE           NUMBER(1)      NOT NULL,
    CREATED_AT          TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_CLINICS PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IX_CLINICS_CODE ON CLINICS (CODE);

CREATE TABLE ROOMS (
    ID           NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CLINIC_ID    NUMBER(10) NOT NULL,
    ROOM_NUMBER  NUMBER(10) NOT NULL,                     -- spoken by the waiting-hall voice
    IS_ACTIVE    NUMBER(1)  NOT NULL,
    CONSTRAINT PK_ROOMS PRIMARY KEY (ID),
    CONSTRAINT FK_ROOMS_CLINIC_ID FOREIGN KEY (CLINIC_ID) REFERENCES CLINICS (ID)
);
CREATE UNIQUE INDEX IX_ROOMS_NUMBER ON ROOMS (ROOM_NUMBER);
CREATE INDEX IX_ROOMS_CLINIC_ID ON ROOMS (CLINIC_ID);

CREATE TABLE DOCTORS (
    ID            NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NAME_AR       NVARCHAR2(100) NOT NULL,
    NAME_EN       NVARCHAR2(100) NOT NULL,
    SPECIALTY_AR  NVARCHAR2(100),
    SPECIALTY_EN  NVARCHAR2(100),
    IS_ACTIVE     NUMBER(1)      NOT NULL,
    CREATED_AT    TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_DOCTORS PRIMARY KEY (ID)
);

-- Daily distribution of doctors to clinics/rooms per shift
CREATE TABLE DOCTOR_ASSIGNMENTS (
    ID                 NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DOCTOR_ID          NUMBER(10)    NOT NULL,
    CLINIC_ID          NUMBER(10)    NOT NULL,
    ROOM_ID            NUMBER(10)    NOT NULL,
    SERVICE_DATE       TIMESTAMP(7)  NOT NULL,            -- date only (00:00)
    SHIFT              NVARCHAR2(20) NOT NULL,            -- Morning | Evening
    STATUS             NVARCHAR2(20) NOT NULL,            -- Scheduled | Active | Paused | Finished
    CURRENT_TICKET_ID  NUMBER(10),                        -- no FK: tickets are deleted daily
    CREATED_AT         TIMESTAMP(7)  NOT NULL,
    CREATED_BY         NVARCHAR2(50),
    CONSTRAINT PK_DOCTOR_ASSIGNMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_DOCTOR_ASSIGNMENTS_DOCTOR_ID FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTORS (ID),
    CONSTRAINT FK_DOCTOR_ASSIGNMENTS_CLINIC_ID FOREIGN KEY (CLINIC_ID) REFERENCES CLINICS (ID),
    CONSTRAINT FK_DOCTOR_ASSIGNMENTS_ROOM_ID   FOREIGN KEY (ROOM_ID)   REFERENCES ROOMS (ID)
);
CREATE UNIQUE INDEX IX_DOCTOR_ASSIGNMENTS_DOCTOR_ID_SERVICE_DATE_SHIFT ON DOCTOR_ASSIGNMENTS (DOCTOR_ID, SERVICE_DATE, SHIFT);
CREATE UNIQUE INDEX IX_DOCTOR_ASSIGNMENTS_ROOM_ID_SERVICE_DATE_SHIFT   ON DOCTOR_ASSIGNMENTS (ROOM_ID, SERVICE_DATE, SHIFT);
CREATE INDEX IX_DOCTOR_ASSIGNMENTS_CLINIC_ID_SERVICE_DATE ON DOCTOR_ASSIGNMENTS (CLINIC_ID, SERVICE_DATE);

CREATE TABLE STAFF_USERS (
    ID             NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USERNAME       NVARCHAR2(40)  NOT NULL,
    PASSWORD_HASH  NVARCHAR2(200) NOT NULL,               -- ASP.NET Core Identity PBKDF2 hash
    DISPLAY_NAME   NVARCHAR2(100) NOT NULL,
    ROLE           NVARCHAR2(20)  NOT NULL,               -- Admin | Receptionist | Doctor | Nurse
    DOCTOR_ID      NUMBER(10),
    IS_ACTIVE      NUMBER(1)      NOT NULL,
    CREATED_AT     TIMESTAMP(7)   NOT NULL,
    LAST_LOGIN_AT  TIMESTAMP(7),
    CONSTRAINT PK_STAFF_USERS PRIMARY KEY (ID),
    CONSTRAINT FK_STAFF_USERS_DOCTOR_ID FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTORS (ID)
);
CREATE UNIQUE INDEX IX_STAFF_USERS_USERNAME ON STAFF_USERS (USERNAME);
CREATE INDEX IX_STAFF_USERS_DOCTOR_ID ON STAFF_USERS (DOCTOR_ID);

CREATE TABLE DISPLAY_DEVICES (
    ID            NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODE          NVARCHAR2(30)  NOT NULL,                -- opened at /display/{CODE}
    NAME          NVARCHAR2(100) NOT NULL,
    CLINIC_IDS    NVARCHAR2(500),                         -- comma-separated, NULL/empty = all
    IS_ACTIVE     NUMBER(1)      NOT NULL,
    LAST_SEEN_AT  TIMESTAMP(7),
    CONSTRAINT PK_DISPLAY_DEVICES PRIMARY KEY (ID)
);
CREATE UNIQUE INDEX IX_DISPLAY_DEVICES_CODE ON DISPLAY_DEVICES (CODE);

CREATE TABLE SYSTEM_SETTINGS (
    SETTING_KEY    NVARCHAR2(60)  NOT NULL,
    SETTING_VALUE  NVARCHAR2(500),           -- nullable: Oracle stores '' as NULL
    UPDATED_AT     TIMESTAMP(7)   NOT NULL,
    UPDATED_BY     NVARCHAR2(50),
    CONSTRAINT PK_SYSTEM_SETTINGS PRIMARY KEY (SETTING_KEY)
);

-- ---------------------------------------------------------------- daily (reset every day)

CREATE TABLE PATIENTS (
    ID            NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SERVICE_DATE  TIMESTAMP(7)   NOT NULL,
    FULL_NAME     NVARCHAR2(100) NOT NULL,
    PHONE         NVARCHAR2(20)  NOT NULL,                -- E.164 +9627XXXXXXXX
    LANGUAGE      NVARCHAR2(2)   NOT NULL,                -- ar | en
    CONSENT_AT    TIMESTAMP(7)   NOT NULL,
    CREATED_AT    TIMESTAMP(7)   NOT NULL,
    CONSTRAINT PK_PATIENTS PRIMARY KEY (ID)
);
CREATE INDEX IX_PATIENTS_SERVICE_DATE_PHONE ON PATIENTS (SERVICE_DATE, PHONE);

CREATE TABLE QUEUE_TICKETS (
    ID                          NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PUBLIC_ID                   NVARCHAR2(32)  NOT NULL,
    SERVICE_DATE                TIMESTAMP(7)   NOT NULL,
    CLINIC_ID                   NUMBER(10)     NOT NULL,
    PATIENT_ID                  NUMBER(10)     NOT NULL,
    SEQ_NO                      NUMBER(10)     NOT NULL,
    TICKET_NUMBER               NVARCHAR2(10)  NOT NULL,   -- e.g. A-015
    COMPLAINT                   NVARCHAR2(500) NOT NULL,
    STATUS                      NVARCHAR2(20)  NOT NULL,   -- Waiting | Called | Completed | NoShow | Transferred | Cancelled | NotSeen
    SOURCE                      NVARCHAR2(20)  NOT NULL,   -- SelfServiceQr | Reception | Transfer
    IS_PRIORITY                 NUMBER(1)      NOT NULL,
    SORT_KEY                    NUMBER(19)     NOT NULL,
    SKIP_COUNT                  NUMBER(10)     NOT NULL,
    RECALL_COUNT                NUMBER(10)     NOT NULL,
    ISSUED_AT                   TIMESTAMP(7)   NOT NULL,
    ORIGINAL_ISSUED_AT          TIMESTAMP(7)   NOT NULL,
    FIRST_CALLED_AT             TIMESTAMP(7),
    LAST_CALLED_AT              TIMESTAMP(7),
    COMPLETED_AT                TIMESTAMP(7),
    ASSIGNMENT_ID               NUMBER(10),
    DOCTOR_ID                   NUMBER(10),
    ROOM_ID                     NUMBER(10),
    TRANSFERRED_FROM_TICKET_ID  NUMBER(10),
    NOTIFIED_ISSUED             NUMBER(1)      NOT NULL,
    NOTIFIED_APPROACHING        NUMBER(1)      NOT NULL,
    NOTIFIED_CALLED             NUMBER(1)      NOT NULL,
    ISSUED_BY                   NVARCHAR2(50),
    CONSTRAINT PK_QUEUE_TICKETS PRIMARY KEY (ID),
    CONSTRAINT FK_QUEUE_TICKETS_CLINIC_ID  FOREIGN KEY (CLINIC_ID)  REFERENCES CLINICS (ID),
    CONSTRAINT FK_QUEUE_TICKETS_PATIENT_ID FOREIGN KEY (PATIENT_ID) REFERENCES PATIENTS (ID)
);
CREATE UNIQUE INDEX IX_QUEUE_TICKETS_PUBLIC_ID ON QUEUE_TICKETS (PUBLIC_ID);
CREATE UNIQUE INDEX IX_QUEUE_TICKETS_SERVICE_DATE_CLINIC_ID_SEQUENCE ON QUEUE_TICKETS (SERVICE_DATE, CLINIC_ID, SEQ_NO);
CREATE INDEX IX_QUEUE_TICKETS_CLINIC_ID_SERVICE_DATE_STATUS_SORT_KEY ON QUEUE_TICKETS (CLINIC_ID, SERVICE_DATE, STATUS, SORT_KEY);
CREATE INDEX IX_QUEUE_TICKETS_PATIENT_ID ON QUEUE_TICKETS (PATIENT_ID);

CREATE TABLE NOTIFICATION_LOG (
    ID                   NUMBER(10)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TICKET_ID            NUMBER(10)      NOT NULL,
    KIND                 NVARCHAR2(20)   NOT NULL,        -- TicketIssued | TurnApproaching | Called
    CHANNEL              NVARCHAR2(20)   NOT NULL,        -- Mock | WhatsApp | Sms
    TO_MASKED            NVARCHAR2(20)   NOT NULL,
    BODY                 NVARCHAR2(1000) NOT NULL,
    STATUS               NVARCHAR2(20)   NOT NULL,        -- Queued | Sent | Failed | Mocked
    PROVIDER_MESSAGE_ID  NVARCHAR2(100),
    ERROR                NVARCHAR2(1000),
    CREATED_AT           TIMESTAMP(7)    NOT NULL,
    SENT_AT              TIMESTAMP(7),
    CONSTRAINT PK_NOTIFICATION_LOG PRIMARY KEY (ID)
);
CREATE INDEX IX_NOTIFICATION_LOG_TICKET_ID ON NOTIFICATION_LOG (TICKET_ID);

-- ---------------------------------------------------------------- permanent (no personal data)

CREATE TABLE AUDIT_LOG (
    ID           NUMBER(10)      GENERATED BY DEFAULT ON NULL AS IDENTITY,
    LOGGED_AT    TIMESTAMP(7)    NOT NULL,
    USERNAME     NVARCHAR2(50)   NOT NULL,
    ACTION       NVARCHAR2(50)   NOT NULL,
    ENTITY_TYPE  NVARCHAR2(50),
    ENTITY_ID    NVARCHAR2(50),
    CLINIC_ID    NUMBER(10),
    DETAILS      NVARCHAR2(1000),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (ID)
);
CREATE INDEX IX_AUDIT_LOG_TIMESTAMP ON AUDIT_LOG (LOGGED_AT);

CREATE TABLE VISIT_HISTORY (
    ID               NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SERVICE_DATE     TIMESTAMP(7)  NOT NULL,
    CLINIC_ID        NUMBER(10)    NOT NULL,
    DOCTOR_ID        NUMBER(10),
    ROOM_ID          NUMBER(10),
    SEQ_NO           NUMBER(10)    NOT NULL,
    TICKET_NUMBER    NVARCHAR2(10) NOT NULL,
    SOURCE           NVARCHAR2(20) NOT NULL,
    OUTCOME          NVARCHAR2(20) NOT NULL,
    IS_PRIORITY      NUMBER(1)     NOT NULL,
    SKIP_COUNT       NUMBER(10)    NOT NULL,
    ISSUED_AT        TIMESTAMP(7)  NOT NULL,
    FIRST_CALLED_AT  TIMESTAMP(7),
    COMPLETED_AT     TIMESTAMP(7),
    WAIT_MINUTES     BINARY_DOUBLE,
    SERVICE_MINUTES  BINARY_DOUBLE,
    ISSUED_HOUR      NUMBER(10)    NOT NULL,
    CONSTRAINT PK_VISIT_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_VISIT_HISTORY_CLINIC_ID FOREIGN KEY (CLINIC_ID) REFERENCES CLINICS (ID)
);
CREATE INDEX IX_VISIT_HISTORY_SERVICE_DATE_CLINIC_ID ON VISIT_HISTORY (SERVICE_DATE, CLINIC_ID);
CREATE INDEX IX_VISIT_HISTORY_CLINIC_ID ON VISIT_HISTORY (CLINIC_ID);

CREATE TABLE DAILY_REPORTS (
    ID                    NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SERVICE_DATE          TIMESTAMP(7)  NOT NULL,
    GENERATED_AT          TIMESTAMP(7)  NOT NULL,
    GENERATED_BY          NVARCHAR2(50),
    RESET_TRIGGER         NVARCHAR2(20) NOT NULL,         -- Scheduled | Manual
    TOTAL_TICKETS         NUMBER(10)    NOT NULL,
    COMPLETED             NUMBER(10)    NOT NULL,
    NO_SHOWS              NUMBER(10)    NOT NULL,
    NOT_SEEN              NUMBER(10)    NOT NULL,
    TRANSFERRED           NUMBER(10)    NOT NULL,
    CANCELLED             NUMBER(10)    NOT NULL,
    AVG_WAIT_MINUTES      BINARY_DOUBLE,
    AVG_SERVICE_MINUTES   BINARY_DOUBLE,
    NOTIFICATIONS_SENT    NUMBER(10)    NOT NULL,
    NOTIFICATIONS_FAILED  NUMBER(10)    NOT NULL,
    AUDIT_EVENT_COUNT     NUMBER(10)    NOT NULL,
    DETAILS_JSON          NCLOB         NOT NULL,         -- per clinic / doctor / hour breakdown
    CONSTRAINT PK_DAILY_REPORTS PRIMARY KEY (ID)
);
CREATE INDEX IX_DAILY_REPORTS_SERVICE_DATE ON DAILY_REPORTS (SERVICE_DATE);
