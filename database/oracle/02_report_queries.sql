-- Useful read-only queries for DBAs / BI (no personal data involved except the live tables).

-- Live queue per clinic right now
SELECT c.CODE, c.NAME_EN, c.STATUS,
       SUM(CASE WHEN t.STATUS = 'Waiting' THEN 1 ELSE 0 END) AS WAITING,
       SUM(CASE WHEN t.STATUS = 'Called'  THEN 1 ELSE 0 END) AS IN_SERVICE,
       SUM(CASE WHEN t.STATUS = 'Completed' THEN 1 ELSE 0 END) AS COMPLETED
FROM CLINICS c
LEFT JOIN QUEUE_TICKETS t ON t.CLINIC_ID = c.ID AND t.SERVICE_DATE = TRUNC(SYSDATE)
GROUP BY c.CODE, c.NAME_EN, c.STATUS, c.SORT_ORDER
ORDER BY c.SORT_ORDER;

-- Average waiting time and patient count per clinic per day (last 30 days)
SELECT TRUNC(v.SERVICE_DATE) AS DAY, c.NAME_EN,
       COUNT(*) AS PATIENTS,
       ROUND(AVG(v.WAIT_MINUTES), 1) AS AVG_WAIT_MIN,
       ROUND(AVG(v.SERVICE_MINUTES), 1) AS AVG_CONSULT_MIN,
       SUM(CASE WHEN v.OUTCOME = 'NoShow' THEN 1 ELSE 0 END) AS NO_SHOWS
FROM VISIT_HISTORY v JOIN CLINICS c ON c.ID = v.CLINIC_ID
WHERE v.SERVICE_DATE >= TRUNC(SYSDATE) - 30
GROUP BY TRUNC(v.SERVICE_DATE), c.NAME_EN
ORDER BY DAY DESC, c.NAME_EN;

-- Peak hours (tickets issued per hour, last 30 days)
SELECT ISSUED_HOUR, COUNT(*) AS TICKETS
FROM VISIT_HISTORY
WHERE SERVICE_DATE >= TRUNC(SYSDATE) - 30
GROUP BY ISSUED_HOUR ORDER BY ISSUED_HOUR;

-- Doctor throughput (last 30 days)
SELECT d.NAME_EN, COUNT(*) AS COMPLETED, ROUND(AVG(v.SERVICE_MINUTES), 1) AS AVG_CONSULT_MIN
FROM VISIT_HISTORY v JOIN DOCTORS d ON d.ID = v.DOCTOR_ID
WHERE v.OUTCOME = 'Completed' AND v.SERVICE_DATE >= TRUNC(SYSDATE) - 30
GROUP BY d.NAME_EN ORDER BY COMPLETED DESC;

-- Audit trail of today
SELECT LOGGED_AT, USERNAME, ACTION, ENTITY_TYPE, ENTITY_ID, DETAILS
FROM AUDIT_LOG WHERE LOGGED_AT >= TRUNC(SYSDATE) ORDER BY LOGGED_AT DESC;
