/// <summary>
/// Arabic-first localisation. The language comes from the request-culture cookie
/// (set by /culture/set) and flows into the Blazor circuit automatically.
/// All texts live here so the hospital can review and edit them in one file.
/// </summary>
public sealed class Loc
{
    public bool IsArabic => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName != "en";
    public string Lang => IsArabic ? "ar" : "en";
    public string Dir => IsArabic ? "rtl" : "ltr";

    public string this[string key] => Get(key, IsArabic);

    public string Format(string key, params object?[] args) =>
        string.Format(CultureInfo.InvariantCulture, this[key], args);

    /// <summary>Translates an OpResult error with its arguments.</summary>
    public string Error(string? key, object[]? args) =>
        key is null ? "" : args is { Length: > 0 } ? string.Format(CultureInfo.InvariantCulture, this[key], args) : this[key];

    public static string Get(string key, bool arabic) =>
        Texts.TryGetValue(key, out var t) ? (arabic ? t.Ar : t.En) : key;

    public static bool Has(string key) => Texts.ContainsKey(key);

    public string Enum<T>(T value) where T : struct, System.Enum => this[$"enum.{typeof(T).Name}.{value}"];

